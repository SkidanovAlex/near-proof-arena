        D, A, m, M, mu, H, n, ell = c['k'] - 1, c['A'], c['m'], c['M'], c['mu'], c['H'], c['n'], c['ell']
        args5 = f'{D} {A} {m} {M} {mu}'
        print(f'theorem dim{i} : firstOrderDimensionCount {args5} = {r["dim"]} := by')
        print(f'  simp only [firstOrderDimensionCount, sum_range_eq_sumTo]; decide +kernel')

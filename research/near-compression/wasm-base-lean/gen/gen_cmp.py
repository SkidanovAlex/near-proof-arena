HERE = os.path.dirname(os.path.abspath(__file__))
BR, D = 37, 33
FLAGS = list(range(5, 16))
names = ['eqz', 'eq', 'ne', 'lts', 'ltu', 'gts', 'gtu', 'les', 'leu', 'ges', 'geu']
def sw_of(i): return 1 if names[i] in ('gts', 'gtu', 'les', 'leu') else 0
def sg_of(i): return 1 if names[i] in ('lts', 'gts', 'les', 'ges') else 0


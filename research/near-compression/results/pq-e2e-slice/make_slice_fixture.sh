#!/usr/bin/env bash
# pq-e2e-slice: regenerate the base-layer fixture (two 5-instruction Wasm calls) and the literal
# AIR source compiled into the recursion crate.
#
# 1. Actual Lean prepare/step fixtures: PreparedCodeTableFixture.lean (default case list).
#    Needs the Lean caches of research/near-compression, spec/lean, spec/lean/v3, zk-formal and
#    formal-core (copy them with `cp -a` from a built worktree, never hard links).
# 2. Byte-packed direct-Wasm AIR (EXEC 157 / CODE 114 / RANGE 24) and witness rows:
#    generate_native_literal_recursion.py --packed-bytes (unchanged generator).
# 3. The AIR part of native_literal.rs (everything before `struct LiteralFixture;`), with the
#    config renamed to SC and the three AIR structs made pub(crate), is written to
#    $NEARPROOF_PQ_DEPS/openvm-sha384/crates/recursion/src/nv/e2e_literal_gen.rs when
#    E2E_INSTALL=1 (it is also part of patches/openvm-recursion-e2e.patch).
#
# Cases: chunk A = "positive" (i32.const 12; i32.const 23; i32.add; drop; end),
#        chunk B = "wrap"     (i32.const -1; i32.const 1;  i32.add; drop; end).
# Both have code length 5 and identical AIR source, hence one base vk.
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
NC=$(cd "$HERE/../.." && pwd)
OUT=$HERE/fixture
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
export PATH=$HOME/.elan/bin:$PATH
(cd "$NC" && lake env lean --run PreparedCodeTableFixture.lean) > "$TMP/cases.json"
python3 - "$TMP" <<'EOF'
import json, sys
tmp = sys.argv[1]
d = json.load(open(f"{tmp}/cases.json"))
for c in d["cases"]:
    if c["label"] in ("positive", "wrap"):
        json.dump(c, open(f"{tmp}/{c['label']}.json", "w"))
EOF
for l in positive wrap; do
  python3 "$NC/airbender/direct-wasm/generate_native_literal_recursion.py" --packed-bytes --no-install \
    --fixture "$TMP/$l.json" --out "$TMP/$l" >/dev/null
  mkdir -p "$OUT/$l"
  cp "$TMP/$l"/{fixture.json,packing.json,public.bin,rows-0.bin,rows-1.bin,rows-2.bin,spec.json} "$OUT/$l/"
done
# The chunk claim V_d reads.  Machine/code fields come from the Lean fixture (actual prepare/step),
# not from the AIR rows; ctx, state roots and the receipt line are STUB placeholders (no AIR reads
# them; they are bound only through the statement digest).
python3 - "$OUT" <<'EOF'
import json, sys, hashlib
out = sys.argv[1]
H = lambda s: hashlib.sha256(s.encode()).hexdigest()
chunk = {"positive": (1000, "A"), "wrap": (1001, "B")}
for label, (height, tag) in chunk.items():
    c = json.load(open(f"{out}/{label}/fixture.json"))
    first, last = c["exec_rows"][0], c["exec_rows"][-1]
    val = lambda v: v["limbs"][0] + 65536 * v["limbs"][1]
    def st(fn, pc, gas, done, fail, stack):
        return " ".join(map(str, [fn, pc, gas, done, fail] + [val(v) for v in stack]))
    assert last["status"] in ("finish", "abort")
    lines = [
        "# pq-e2e-slice chunk claim v0. STUB = carried in the statement, read by no AIR.",
        "chain_id slice-testnet",
        f"height {height}",
        f"prev_block_hash {H('pq-e2e-slice/prev-block/' + tag)}",
        "gas_price 100000000",
        "protocol_version 86",
        f"pre_state_root {H('pq-e2e-slice/pre-state/' + tag)}",
        f"receipt slice.test {c['method']} {c['prepaid']} {hashlib.sha256(bytes(c['wasm_bytes'])).hexdigest()}",
        "entry " + st(first["before"]["frames"][0]["fn"], first["pc"], first["before"]["gas"]["g"], 0, 0, first["before"]["stack"]),
    ]
    for e in c["code"]:
        ch = e["charge"]
        has, kind, fee = (0, 0, 0) if ch is None else (1, ch["kind"], ch["constant"])
        lines.append(f"code {e['pc']} {e['function']} {e['instruction']['opcode']} {e['instruction']['immediate']} {has} {kind} {fee}")
    lines += [
        f"post_state_root {H('pq-e2e-slice/post-state/' + tag)}",
        "final " + st(0, last["pc"], last["after"]["gas"]["g"], 1, int(last["status"] == "abort"), last["after"]["stack"]),
    ]
    open(f"{out}/{label}/claim.txt", "w").write("\n".join(lines) + "\n")
EOF
cmp -s "$TMP/positive/native_literal.rs" "$TMP/wrap/native_literal.rs" || { echo "AIR source differs between cases" >&2; exit 1; }
python3 - "$TMP/positive/native_literal.rs" "$TMP/e2e_literal_gen.rs" <<'EOF'
import sys, re
s = open(sys.argv[1]).read()
s = s[: s.index("struct LiteralFixture;")]
s = s.replace("BabyBearPoseidon2Config", "SC")
s = re.sub(r"^struct Literal(\d+);", r"pub(crate) struct Literal\1;", s, flags=re.M)
hdr = "// GENERATED by results/pq-e2e-slice/make_slice_fixture.sh from generate_native_literal_recursion.py\n// --packed-bytes (code length 5). Do not edit.\n"
open(sys.argv[2], "w").write(hdr + s)
EOF
sha256sum "$TMP/e2e_literal_gen.rs" | cut -d' ' -f1 > "$OUT/e2e_literal_gen.sha256"
if [ "${E2E_INSTALL:-0}" = 1 ]; then
  DEPS=${NEARPROOF_PQ_DEPS:-/data/illia/nearproof-deps/pq-e2e}
  cp "$TMP/e2e_literal_gen.rs" "$DEPS/openvm-sha384/crates/recursion/src/nv/e2e_literal_gen.rs"
fi
echo "fixture OK: $OUT"

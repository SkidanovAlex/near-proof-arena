#!/usr/bin/env bash
# lane/pq-cpu-prover identity harness: one NV layer (bench/nv_layer.rs) at the real lever settings,
# prints the proof SHA-256.   identity.sh <binary> <cfg> [extra env...]
#   cfg: q42 | q48 (NV_LOG_ROWS=14, n_stack 15) | s42 | s48 (NV_LOG_ROWS=16, n_stack 16)
#        | real (NvAir 2^18, SHA 2^20 fixed heights, n_stack 18, b 1, 42 B)
set -euo pipefail
BIN=$1 CFG=$2; shift 2
COMMON="NEARPROOF_TSTAR=1 PARENT_LOG_BLOWUP=1 PARENT_K=4 PARENT_K1=1 PARENT_BITS=236 PARENT_QUERY_POW=0 PARENT_LIST_M=3 PARENT_X15=15 PARENT_MULTIPROOF=1 PARENT_KEEP_DOMAIN=1 PARENT_GRUEN_GKR=1 PARENT_GKR_DERIVE=1 PARENT_GRUEN_ZC=1 PARENT_NEXT_MASK=1 PARENT_WHIR_Y=1 PARENT_TIGHT=1 PARENT_WIDE_POW=1 NV_TRACE=${NV_TRACE:-0}"
case $CFG in
  q42) C="NEARPROOF_DIGEST_BYTES=42 NEARPROOF_COSET_LEAF=1 NV_LOG_ROWS=14 NV_PROG_LOG=13 PARENT_N_STACK=15";;
  q48) C="NEARPROOF_DIGEST_BYTES=48 NEARPROOF_COSET_LEAF=0 NV_LOG_ROWS=14 NV_PROG_LOG=13 PARENT_N_STACK=15";;
  s42) C="NEARPROOF_DIGEST_BYTES=42 NEARPROOF_COSET_LEAF=1 NV_LOG_ROWS=16 PARENT_N_STACK=16";;
  s48) C="NEARPROOF_DIGEST_BYTES=48 NEARPROOF_COSET_LEAF=0 NV_LOG_ROWS=16 PARENT_N_STACK=16";;
  fx42) C="NEARPROOF_DIGEST_BYTES=42 NEARPROOF_COSET_LEAF=1 PARENT_K1=0";;
  fx48) C="NEARPROOF_DIGEST_BYTES=48 NEARPROOF_COSET_LEAF=0 PARENT_K1=0";;
  real) C="NEARPROOF_DIGEST_BYTES=42 NEARPROOF_COSET_LEAF=1 NV_LOG_ROWS=18 PARENT_N_STACK=18 NV_FIXED=${NV_FIXED:-262144,1048576,256,65536}";;
  *) echo "bad cfg"; exit 1;;
esac
env $COMMON $C RAYON_NUM_THREADS=${RAYON_NUM_THREADS:-8} "$@" nice -n ${NICE:-10} taskset -c ${CPUS:-0-7} \
  /data/illia/nearproof-deps/bin/heavy "$BIN"

"""Literal control AIR generation; kernel membership proofs remain separate.

Every table constraint and interaction is emitted without simplification.
Whole-export parity checks include generated multiplicity-bit constraints.
"""
from pathlib import Path
from prepared_control_air import exec_table, code_table, boundary
from generate_prepared_literal import expression


def expr_list(es):
    return '[' + ','.join(expression(e) for e in es) + ']'


def generate():
    lines = ['-- Generated by airbender/direct-wasm/generate_prepared_control_literal.py.',
             'import ZkFormal.V2.VerifierDefs', '', 'namespace NearCompression',
             'open ZkFormal.Air ZkFormal.V2', 'set_option maxRecDepth 65536', '']
    tables = [('Exec', exec_table()), ('Code', code_table())]
    for label, es in [(label, t['constraints']) for label, t in tables] + [('Boundary', boundary())]:
        names = []
        for i, e in enumerate(es):
            name = f'preparedControlLiteral{label}{i:04d}'
            names.append(name)
            lines.append(f'def {name} : Expr := {expression(e)}')
        lines.append(f'def preparedControlLiteral{label} : List Expr := [\n  ' + ',\n  '.join(names) + ']\n')
    for label, table in tables:
        interactions = []
        for interaction in table['interactions']:
            interactions.append('{bus:=' + str(interaction['bus']) + ',send:=' + str(interaction['send']).lower() +
                                ',mult:=' + expr_list(interaction['mult']) + ',msg:=' + expr_list(interaction['msg']) + '}')
        lines.append(f'def preparedControlLiteral{label}Table : Table :=\n' +
                     '{width:=' + str(table['width']) + ',maxLog:=' + str(table['maxLog']) +
                     ',constraints:=preparedControlLiteral' + label + ',interactions:=[' + ',\n'.join(interactions) + ']}\n')
    lines += ['def preparedControlLiteralAir (codeLength : Nat) : AirP :=',
              '  {tables:=[preparedControlLiteralExecTable,preparedControlLiteralCodeTable],',
              '   numBuses:=4,numPub:=66+29*codeLength,maxPub:=66+29*codeLength,pubSegs:=[',
              '     {bus:=0,send:=false,width:=27,countAt:=0,start:=12},',
              '     {bus:=1,send:=false,width:=27,countAt:=4,start:=39},',
              '     {bus:=3,send:=false,width:=29,countAt:=8,start:=66}]}',
              '', 'end NearCompression', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    root = Path(__file__).resolve().parents[2]
    (root/'NearCompression/PreparedControlLiteral.lean').write_text(generate())

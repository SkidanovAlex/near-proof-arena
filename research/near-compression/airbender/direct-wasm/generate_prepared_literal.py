"""Generate literal Lean constraint ASTs; trust comes from kernel certificates.

No JSON parser is inserted into a theorem. The separate export parity check
compares every expression and explicitly handles automatic multiplicity bits.
"""
from pathlib import Path
from prepared_code_table_air import exec_table, code_table, boundary


def expression(e):
    tag=e[0]
    if tag=='c': return f'(.const {e[1]})'
    if tag=='v': return f'(.col {e[1]} {"true" if e[2] else "false"})'
    if tag=='p': return f'(.pub {e[1]})'
    if tag in ('first','last','trans'):return {'first':'.isFirst','last':'.isLast','trans':'.isTransition'}[tag]
    if tag in ('+','*'):return f'(.{ {"+":"add","*":"mul"}[tag]} {expression(e[1])} {expression(e[2])})'
    if tag=='-':return f'(.neg {expression(e[1])})'
    raise ValueError(e)


def generate():
    lines=['-- Generated by airbender/direct-wasm/generate_prepared_literal.py.',
           'import NearCompression.PreparedCodeBus','',
           'namespace NearCompression','open ZkFormal.Air ZkFormal.V2',
           'set_option maxRecDepth 65536','']
    for label,exprs in [('Exec',exec_table()['constraints']),('Code',code_table()['constraints']),('Boundary',boundary())]:
        names=[]
        for i,e in enumerate(exprs):
            name=f'preparedLiteral{label}{i:04d}';names.append(name)
            lines.append(f'def {name} : Expr := {expression(e)}')
        lines.append(f'def preparedLiteral{label} : List Expr := [\n  '+',\n  '.join(names)+']\n')
    lines+=['def preparedLiteralAir (codeLength : Nat) : AirP :=',
            '  preparedCodeBusAir preparedLiteralExec preparedLiteralCode preparedLiteralBoundary codeLength',
            '', 'end NearCompression','']
    return '\n'.join(lines)

if __name__=='__main__':
    root=Path(__file__).resolve().parents[2]
    (root/'NearCompression/PreparedLiteral.lean').write_text(generate())

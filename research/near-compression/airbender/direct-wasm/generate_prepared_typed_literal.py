"""Exact typed AIR export. Named expressions are deduplicated, never simplified."""
from pathlib import Path
import json
from prepared_typed_air import exec_table,code_table,boundary
from generate_prepared_literal import expression

def expr_list(es):return '['+','.join(expression(e) for e in es)+']'
def generate():
 lines=['-- Generated by airbender/direct-wasm/generate_prepared_typed_literal.py.',
  'import ZkFormal.V2.VerifierDefs','','namespace NearCompression','open ZkFormal.Air ZkFormal.V2','set_option maxRecDepth 65536','']
 known={};groups={};index=0
 for count in [4,0,1,2,3]:
  names=[]
  for e in exec_table(count)['constraints']:
   key=json.dumps(e,separators=(',',':'))
   if key not in known:
    name=f'preparedTypedLiteralExec{index:04d}';index+=1;known[key]=name
    lines.append(f'def {name} : Expr := {expression(e)}')
   names.append(known[key])
  groups[count]=names
 for count in range(5):
  lines.append(f'def preparedTypedLiteralExecCount{count} : List Expr := [\n  '+',\n  '.join(groups[count])+']\n')
 lines+=['def preparedTypedLiteralExec (count : Nat) : List Expr :=',
  '  if count=0 then preparedTypedLiteralExecCount0 else if count=1 then preparedTypedLiteralExecCount1',
  '  else if count=2 then preparedTypedLiteralExecCount2 else if count=3 then preparedTypedLiteralExecCount3',
  '  else preparedTypedLiteralExecCount4','']
 for label,es in [('Code',code_table()['constraints']),('Boundary',boundary())]:
  names=[]
  for i,e in enumerate(es):
   name=f'preparedTypedLiteral{label}{i:04d}';names.append(name);lines.append(f'def {name} : Expr := {expression(e)}')
  lines.append(f'def preparedTypedLiteral{label} : List Expr := [\n  '+',\n  '.join(names)+']\n')
 for label,table in [('Exec',exec_table(4)),('Code',code_table())]:
  interactions=['{bus:='+str(it['bus'])+',send:='+str(it['send']).lower()+',mult:='+expr_list(it['mult'])+',msg:='+expr_list(it['msg'])+'}' for it in table['interactions']]
  lines.append(f'def preparedTypedLiteral{label}Table'+(' (count : Nat)' if label=='Exec' else '')+' : Table :=\n'+
   '{width:='+str(table['width'])+',maxLog:='+str(table['maxLog'])+',constraints:=preparedTypedLiteral'+label+(' count' if label=='Exec' else '')+',interactions:=['+','.join(interactions)+']}\n')
 lines+=['def preparedTypedLiteralAir (codeLength localCount : Nat) : AirP :=',
  '  {tables:=[preparedTypedLiteralExecTable localCount,preparedTypedLiteralCodeTable],',
  '   numBuses:=4,numPub:=118+37*codeLength,maxPub:=118+37*codeLength,pubSegs:=[',
  '     {bus:=0,send:=false,width:=51,countAt:=0,start:=12},',
  '     {bus:=1,send:=false,width:=51,countAt:=4,start:=63},',
  '     {bus:=3,send:=false,width:=37,countAt:=8,start:=118}]}','','end NearCompression','']
 return '\n'.join(lines)
if __name__=='__main__':
 (Path(__file__).resolve().parents[2]/'NearCompression/PreparedTypedLiteral.lean').write_text(generate())

"""Larger field/digest geometry and partial QROM ledger; no certification."""
import hashlib
import json
from fractions import Fraction as F
from pathlib import Path
from screen_weighted_code_switch import stage, optimize, simulate, RATES
from report_code_switch_algebra import mca, bits
from report_code_switch_qrom import bound
from pq384_ext8_reference import P
ROOT=Path(__file__).resolve().parents[2]


def ledger(path,extension,c):
    algebra=F(0);query=F(0)
    for s in path:
        d,b,k,q=s['degree'],s['rate'],s['skipped'],s['queries']
        algebra+=sum((mca(d//(1<<i),b)[0] for i in range(k)),F(0))
        L=10*s['next_rate'];nd=d//(1<<k)
        algebra+=F(L*(L-1),2)*(nd-1)+L*(1+q*(1<<k))+20*b*k
        import math
        query+=F(21,20*math.isqrt(b))**q
    epsilon=algebra/P**extension+query
    result=bound(2**128,epsilon,512,2**c)
    return dict(algebra_bits=bits(algebra/P**extension),query_sum_bits=bits(query),
                partial_QROM_bound=str(result),partial_QROM_bound_float=float(result),
                partial_within_half_success=result<=F(1,2))


def main():
    results=[]
    for extension in (8,10,12):
        for c,budget in ((0,262),(8,270)):
            candidates=[]
            for packing in (16,32,64,128,256):
                d=256*packing
                # Source803 base columns; auxiliary53 extension columns.
                widths=tuple(8*((w+packing-1)//packing) for w in (803,53*extension))
                for k in range(1,9):
                    edge=stage(d,4,k,'johnson',widths,budget,extension,64)
                    for nr in RATES:
                        cost,path=optimize(d//(1<<k),nr,'johnson',budget,extension,64)
                        # Freeze the measured local/GKR scalar COUNT, not byte count.
                        fixed=8+12*extension*(d.bit_length()-1)+1604*4*extension
                        candidates.append(dict(packing=packing,fixed_bytes=fixed,
                            expected_subtotal_bytes=fixed+edge['expected_bytes']+cost,
                            path=[dict(edge,next_rate=nr)]+path))
            best=min(candidates,key=lambda x:x['expected_subtotal_bytes'])
            trials=[simulate(best['path'],82701+s,extension,64) for s in range(16)]
            sizes=[t['bytes']+best['fixed_bytes'] for t in trials]
            results.append(dict(extension=extension,hash_bytes=64,assumed_log2_C=c,
                isolated_query_bits=budget,best=best,min_subtotal_bytes=min(sizes),
                max_subtotal_bytes=max(sizes),trials=trials,
                conditional_ledger=ledger(best['path'],extension,c)))
    report=dict(status='COUNTERFACTUAL_LARGER_FIELD_SIZE_AND_PARTIAL_QROM_SCREEN',results=results,
        scope='All source cosets and Merkle frontiers priced. Auxiliary coordinate width scales53*extension; '
              'base source width803 retained. Ext scalars4*extension bytes; hash nodes64bytes. '
              'Local/GKR count1604 scalars frozen; compiler layout can change and has NOT been measured. '
              'Public envelope excluded. Fields10/12 are arithmetic projections, not implemented/certified extensions. '
              'Ledger assumes Johnson/MCA, repeated weighted composition and QROM compiler applicability; none established. '
              'Ledger recomputed for selected query counts/schedule but excludes local/GKR/bus/initial-reduction errors. '
              'C1/256 nominal, not certified constants. Q=2^128 includes overhead, target probability1/2. '
              'No feasibility gate changed. This finite search is not a protocol size lower bound.',
        default_regression='Original Ext8/SHA384 report regenerated byte-identically after parameterizing geometry helpers.')
    (ROOT/'results/larger-field-code-switch-screen.json').write_text(json.dumps(report,indent=2)+'\n')
    for r in results:
        print(r['extension'],r['assumed_log2_C'],r['min_subtotal_bytes'],r['max_subtotal_bytes'],
              r['conditional_ledger']['partial_within_half_success'],r['conditional_ledger']['algebra_bits'])

if __name__=='__main__':main()
